//! Traits describing which row callbacks a generated table accessor supports.
//!
//! [`TableSource`] is implemented for every `spacetime generate` table accessor, and [`OnInsert`],
//! [`OnDelete`], and [`OnUpdate`] for the accessors whose table reports that kind of change. The
//! [`StdbPlugin`](crate::prelude::StdbPlugin) table methods are bounded by these traits.
use super::policy::carries_ctx;
use crate::{
    channel_bridge::{channel_sender, register_channel},
    message::{RowEvent, TableChange},
};
use bevy_app::App;
use bevy_ecs::prelude::World;
use spacetimedb_sdk::__codegen::{
    DbContext, InModule, SpacetimeModule, TableAccessor, TableLike, WithDelete, WithInsert,
    WithUpdate,
};
use std::any::TypeId;

/// The event context passed to the row callbacks of `TRow`'s module.
type RowEventContext<TRow> = <<TRow as InModule>::Module as SpacetimeModule>::EventContext;

mod sealed {
    pub trait Sealed<C> {}
}

/// A `spacetime generate` table accessor whose row changes can be forwarded into Bevy.
///
/// This trait is sealed, and implemented for every generated accessor.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a table accessor for this connection",
    note = "pass a `...TableAccessor` type generated by `spacetime generate` for the same module as the plugin"
)]
pub trait TableSource<C: DbContext>: sealed::Sealed<C> + 'static {
    /// Returns the [`TypeId`] of the row type, which keys its [`TableChange`] channel.
    #[doc(hidden)]
    fn row_type() -> TypeId;

    /// Registers the [`TableChange`] channel for the row type.
    #[doc(hidden)]
    fn register_channel(app: &mut App);
}

/// A [`TableSource`] that reports inserted rows. Every table, view, and event table does.
#[diagnostic::on_unimplemented(message = "`{Self}` does not report inserted rows")]
pub trait OnInsert<C: DbContext>: TableSource<C> {
    /// Registers an `on_insert` callback that sends to the row type's channel.
    #[doc(hidden)]
    fn bind_insert(world: &World, db: &C::DbView);
}

/// A [`TableSource`] that reports deleted rows. Tables and views do; event tables do not.
#[diagnostic::on_unimplemented(
    message = "`{Self}` does not report deleted rows",
    note = "an event table only reports inserts: register it with `add_event_table`"
)]
pub trait OnDelete<C: DbContext>: TableSource<C> {
    /// Registers an `on_delete` callback that sends to the row type's channel.
    #[doc(hidden)]
    fn bind_delete(world: &World, db: &C::DbView);
}

/// A [`TableSource`] that reports updated rows. Only tables with a primary key do.
#[diagnostic::on_unimplemented(
    message = "`{Self}` does not report updated rows",
    note = "only a table with a primary key does: register this one with `add_table_without_pk`, `add_view`, or `add_event_table`"
)]
pub trait OnUpdate<C: DbContext>: TableSource<C> {
    /// Registers an `on_update` callback that sends to the row type's channel.
    #[doc(hidden)]
    fn bind_update(world: &World, db: &C::DbView);
}

impl<C, T> sealed::Sealed<C> for T
where
    C: DbContext,
    T: TableAccessor<C::DbView>,
{
}

impl<C, T> TableSource<C> for T
where
    C: DbContext,
    T: TableAccessor<C::DbView> + 'static,
    T::Row: Send + Sync + InModule + 'static,
    RowEvent<T::Row>: Send + Sync,
{
    fn row_type() -> TypeId {
        TypeId::of::<T::Row>()
    }

    fn register_channel(app: &mut App) {
        register_channel::<TableChange<T::Row>>(app);
    }
}

impl<C, T> OnInsert<C> for T
where
    C: DbContext,
    T: TableSource<C> + TableAccessor<C::DbView>,
    T::Row: Send + Sync + Clone + InModule + 'static,
    RowEvent<T::Row>: Send + Sync + Clone,
    for<'db> T::Handle<'db>:
        TableLike<Row = T::Row, EventContext = RowEventContext<T::Row>> + WithInsert,
{
    fn bind_insert(world: &World, db: &C::DbView) {
        let sender = channel_sender::<TableChange<T::Row>>(world);
        let with_ctx = carries_ctx::<T::Row>(world);
        T::get(db).on_insert(move |ctx, row| {
            let _ = sender.send(TableChange::Insert {
                ctx: with_ctx.then(|| event_of::<T::Row>(ctx).clone()).into(),
                row: row.clone(),
            });
        });
    }
}

impl<C, T> OnDelete<C> for T
where
    C: DbContext,
    T: TableSource<C> + TableAccessor<C::DbView>,
    T::Row: Send + Sync + Clone + InModule + 'static,
    RowEvent<T::Row>: Send + Sync + Clone,
    for<'db> T::Handle<'db>:
        TableLike<Row = T::Row, EventContext = RowEventContext<T::Row>> + WithDelete,
{
    fn bind_delete(world: &World, db: &C::DbView) {
        let sender = channel_sender::<TableChange<T::Row>>(world);
        let with_ctx = carries_ctx::<T::Row>(world);
        T::get(db).on_delete(move |ctx, row| {
            let _ = sender.send(TableChange::Delete {
                ctx: with_ctx.then(|| event_of::<T::Row>(ctx).clone()).into(),
                row: row.clone(),
            });
        });
    }
}

impl<C, T> OnUpdate<C> for T
where
    C: DbContext,
    T: TableSource<C> + TableAccessor<C::DbView>,
    T::Row: Send + Sync + Clone + InModule + 'static,
    RowEvent<T::Row>: Send + Sync + Clone,
    for<'db> T::Handle<'db>:
        TableLike<Row = T::Row, EventContext = RowEventContext<T::Row>> + WithUpdate,
{
    fn bind_update(world: &World, db: &C::DbView) {
        let sender = channel_sender::<TableChange<T::Row>>(world);
        let with_ctx = carries_ctx::<T::Row>(world);
        T::get(db).on_update(move |ctx, old, new| {
            let _ = sender.send(TableChange::Update {
                ctx: with_ctx.then(|| event_of::<T::Row>(ctx).clone()).into(),
                old: old.clone(),
                new: new.clone(),
            });
        });
    }
}

/// Returns the event carried by a row callback's context.
fn event_of<TRow: InModule>(ctx: &RowEventContext<TRow>) -> &RowEvent<TRow> {
    use spacetimedb_sdk::__codegen::AbstractEventContext;
    ctx.event()
}
